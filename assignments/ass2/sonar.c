/**
 ******************************************************************************
 * @file    sonar.c
 * @brief   Raw reading of the HC-SR04 ultrasonic sensor. See sonar.h.
 *
 *          TIM5 counts up from 0 and restarts every 100 ms. The trigger pulse
 *          (CH1) is high at the start of each period. CH2 captures the count
 *          at every edge of ECHO; reading the ECHO pin right after the edge
 *          tells whether it was the rising or the falling one.
 *
 * @course  Microprocessor-Based Product Design, Technion
 ******************************************************************************
 */
#include "sonar.h"

extern TIM_HandleTypeDef htim5;      /* generated by CubeMX in main.c   */

/* written in the interrupt (B.2), so volatile */
static volatile uint32_t riseCount    = 0;  /* capture at the rising edge */
static volatile uint8_t  haveRise     = 0;  /* 1 = waiting for the falling edge */
static volatile uint32_t rawReading   = 0;
static volatile uint32_t readingCount = 0;
static volatile uint32_t missedCount  = 0;

/* ------------------------------------------------------------------ */
/* One captured edge: rising stores the count, falling ends a reading  */
/* ------------------------------------------------------------------ */
static uint8_t handleEdge(uint32_t capture)
{
  if (HAL_GPIO_ReadPin(SONAR_ECHO_PORT, SONAR_ECHO_PIN) == GPIO_PIN_SET) {
    riseCount = capture;               /* rising edge: ECHO is high now */
    haveRise  = 1;
    return 0;
  }

  if (!haveRise) {
    return 0;                          /* falling edge without its rise */
  }

  /* falling edge: the counter may have restarted in between */
  uint32_t period = __HAL_TIM_GET_AUTORELOAD(&htim5) + 1u;
  rawReading = (capture >= riseCount) ? (capture - riseCount)
                                      : (capture + period - riseCount);
  haveRise = 0;
  readingCount++;
  return 1;
}

/* ------------------------------------------------------------------ */
/* Start                                                               */
/* ------------------------------------------------------------------ */
static void startTrigger(void)
{
  __HAL_TIM_SET_COMPARE(&htim5, TIM_CHANNEL_1, SONAR_TRIG_COUNTS);
  HAL_TIM_PWM_Start(&htim5, TIM_CHANNEL_1);        /* TRIG, PB2  */
}

void sonarStartPolling(void)
{
  HAL_TIM_IC_Start(&htim5, TIM_CHANNEL_2);         /* ECHO, PC12 */
  startTrigger();
}

void sonarStartInterrupt(void)
{
  HAL_TIM_IC_Start_IT(&htim5, TIM_CHANNEL_2);      /* ECHO, PC12 */
  startTrigger();
}

/* ------------------------------------------------------------------ */
/* Polling mode: call as often as possible from the main loop          */
/* ------------------------------------------------------------------ */
uint8_t sonarPoll(void)
{
  if (!__HAL_TIM_GET_FLAG(&htim5, TIM_FLAG_CC2)) {
    return 0;                          /* no new edge since last time   */
  }

  /* reading the captured value also clears the CC2 flag */
  uint32_t capture = HAL_TIM_ReadCapturedValue(&htim5, TIM_CHANNEL_2);

  if (__HAL_TIM_GET_FLAG(&htim5, TIM_FLAG_CC2OF)) {
    /* overcapture: a second edge came before the first was read, so the
       first one is lost and this reading cannot be completed */
    __HAL_TIM_CLEAR_FLAG(&htim5, TIM_FLAG_CC2OF);
    haveRise = 0;
    missedCount++;
    return 0;
  }

  return handleEdge(capture);
}

/* ------------------------------------------------------------------ */
/* Interrupt mode: call from HAL_TIM_IC_CaptureCallback(htim)          */
/* ------------------------------------------------------------------ */
uint8_t sonarCaptureEdge(TIM_HandleTypeDef *htim)
{
  if (htim->Instance != TIM5 || htim->Channel != HAL_TIM_ACTIVE_CHANNEL_2) {
    return 0;                          /* another timer or channel      */
  }
  return handleEdge(HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_2));
}

/* ------------------------------------------------------------------ */
/* Results                                                             */
/* ------------------------------------------------------------------ */
uint32_t sonarGetRaw(void)          { return rawReading; }
uint32_t sonarGetReadingCount(void) { return readingCount; }
uint32_t sonarGetMissedCount(void)  { return missedCount; }
