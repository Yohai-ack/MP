/**
 ******************************************************************************
 * @file    ass2.h
 * @brief   Assignment 2 reference solution: task numbers and shared helpers.
 *          TA ONLY, never handed to students.
 *
 *          All parts live in one program. What runs is chosen by writing a
 *          task number into the global variable `task` in Live Expressions.
 *          Digits: part (1 = A ... 5 = E), item, sub-item (0 = no sub-items).
 *          Every result line printed to PuTTY starts with its tag (A1.1:,
 *          B2.2:, C1:, ...) in the format the instructions prescribe.
 ******************************************************************************
 */
#ifndef ASS2_H
#define ASS2_H

#include "main.h"
#include <stdint.h>

/* ------------------------------------------------------------------ */
/* task numbers (write one of these into `task`)                       */
/* ------------------------------------------------------------------ */
enum
{
    TASK_IDLE  = 0,
    TASK_A1_1  = 111,   /* polling PWM on LD2, N and M from Live Expr. */
    TASK_A1_2  = 112,   /* the same, M = N/2 kept by the code          */
    TASK_A2_1  = 121,   /* TIM7 interrupt PWM on LD2                   */
    TASK_A2_2  = 122,   /* TIM7 interrupt PWM on wheel 1               */
    TASK_A2_3  = 123,   /* TIM7 at 10 kHz for 2 s, then at 1.7 MHz     */
    TASK_A2_4  = 124,   /* time 1000 setLedChannel calls               */
    TASK_A3_1  = 131,   /* hardware PWM: duty sweep on wheel 1         */
    TASK_A3_2  = 132,   /* LED 0 by the PCA9634, wheel 1 at 50 %       */
    TASK_B1    = 210,   /* ultrasonic calibration                      */
    TASK_B2_1  = 221,   /* IR hand passes, polling                     */
    TASK_B2_2  = 222,   /* IR hand passes, interrupts                  */
    TASK_B3_1  = 231,   /* ultrasonic hand passes, polling             */
    TASK_B3_2  = 232,   /* ultrasonic hand passes, interrupts          */
    TASK_C1    = 310,   /* I2C bus scan                                */
    TASK_C2    = 320,   /* own PCA9634 driver: 8 colours               */
    TASK_C3    = 330,   /* 8 single writes vs one burst                */
    TASK_C4    = 340,   /* buttons, HAL return values                  */
    TASK_C5    = 350,   /* servo through the PCA9685                   */
    TASK_D1_1  = 411,   /* by hand, Encoder Mode TI1                   */
    TASK_D1_2  = 412,   /* by hand, Encoder Mode TI1 and TI2           */
    TASK_D1_3  = 413,   /* motor at 50 %, one run in each mode         */
    TASK_D2    = 420,   /* speed: naive vs (int16_t) difference        */
    TASK_E1    = 510,   /* calibration of the four wheels (own design) */
    TASK_E2_1  = 521,   /* step response, wheel 1                      */
    TASK_E2_2  = 522,   /* wheel 2                                     */
    TASK_E2_3  = 523,   /* wheel 3                                     */
    TASK_E2_4  = 524    /* wheel 4                                     */
};

extern volatile uint16_t task;       /* Live Expressions: what runs    */

/* timers generated by CubeMX in main.c */
extern TIM_HandleTypeDef htim1;      /* encoder of wheel 1             */
extern TIM_HandleTypeDef htim8;      /* encoder of wheel 2             */
extern TIM_HandleTypeDef htim3;      /* encoder of wheel 3             */
extern TIM_HandleTypeDef htim4;      /* encoder of wheel 4             */
extern TIM_HandleTypeDef htim2;      /* motor PWM, 17 kHz              */
extern TIM_HandleTypeDef htim5;      /* ultrasonic trigger and echo    */
extern TIM_HandleTypeDef htim6;      /* 100 Hz sample interrupt        */
extern TIM_HandleTypeDef htim7;      /* 10 kHz software PWM interrupt  */
extern I2C_HandleTypeDef hi2c1;

/* ------------------------------------------------------------------ */
/* wheel 1                                                              */
/* ------------------------------------------------------------------ */
#define PWM_FULL          10000u     /* TIM2 period + 1: CCR = 10000 is 100 % */
#define IR_OBSTACLE_LEVEL GPIO_PIN_SET   /* PA7 level of an obstacle (A1 Part E): HIGH on our cart */
#define COUNTS_PER_REV_TI1  660.0f   /* D.1.1 on our cart (2026-11-04): 661 and 663 by hand */
#define COUNTS_PER_REV      1320.0f  /* TI1 and TI2, the better resolution, used from D.2 on
                                        (2026-11-04: factor 2.00 to 2.01 to TI1) */
#define TWO_PI              6.2831853f

void    wheel1Forward(uint8_t forward);  /* DIR1: SET is forward       */
void    wheel1Duty(uint32_t percent);    /* 0..100 %                   */
void    encoderSetMode(uint32_t mode);   /* TIM1: TIM_ENCODERMODE_TI1 / _TI12 */
void    encoderSetModeOf(TIM_HandleTypeDef *htim, uint32_t mode);   /* any encoder timer */

/* the four wheels (E): motor channel, DIR pin, encoder timer, and the
   sign that makes "forward" positive, found in E.1 on our cart        */
typedef struct
{
    volatile uint32_t *ccr;          /* TIM2->CCR1 .. CCR4              */
    GPIO_TypeDef      *dirPort;
    uint16_t           dirPin;
    GPIO_PinState      forwardLevel; /* DIR level that drives it forward */
    TIM_HandleTypeDef *enc;          /* its encoder timer               */
    int8_t             countSign;    /* +1: counts up when forward      */
} Wheel;

extern const Wheel wheels[4];        /* wheels[0] is wheel 1            */
void    wheelRun(uint8_t w, uint32_t percent);   /* w = 0..3, forward   */

/* ------------------------------------------------------------------ */
/* shared helpers (ass2_common.c)                                      */
/* ------------------------------------------------------------------ */
void    taskDone(uint16_t myTask);              /* end of a task       */
uint8_t waitMs(uint16_t myTask, uint32_t ms);   /* 0 if task changed   */
void    printFixed2(float value);               /* 12.34, no %f needed */
void    printBinary(uint32_t value, uint8_t nBits);

/* main-loop passes per second: call passCount() once per pass; it
   returns 1 once a second, with the count of the last second in *n    */
typedef struct
{
    uint32_t passes;
    uint32_t startTick;
} PassCounter;

void    passStart(PassCounter *p);
uint8_t passCount(PassCounter *p, uint32_t *n);

/* ------------------------------------------------------------------ */
/* the parts (partA.c ... partE.c)                                     */
/* ------------------------------------------------------------------ */
void partA1(uint16_t myTask);           /* 111, 112 */
void partA2(uint16_t myTask);           /* 121, 122, 123 */
void partA2Tick(void);                  /* TIM7 callback */
void partA2_4(void);
void partA3_1(void);
void partA3_2(void);

void partB1(void);
void partB2B3(uint16_t myTask);         /* 221, 222, 231, 232 */
void partBIrEdge(void);                 /* EXTI callback of PA7 */
void partBSonarReading(void);           /* a new ultrasonic reading (interrupt) */

void partC1(void);
void partC2(void);
void partC3(void);
void partC4(void);
void partC5(void);

void partD1(uint16_t myTask);           /* 411, 412, 413 */
void partD2(void);
void partD2Sample(void);                /* TIM6 callback */

void partE1(void);                      /* 510 */
void partE2(uint16_t myTask);           /* 521 to 524 */
void partE2Sample(void);                /* TIM6 callback */

uint8_t b1Pressed(void);                /* 1 once per press of B1 (PC13, HIGH when pressed) */

/* ------------------------------------------------------------------ */
/* the dispatcher (ass2_tasks.c)                                       */
/* ------------------------------------------------------------------ */
void ass2Init(void);       /* call once in USER CODE BEGIN 2           */
void ass2Run(void);        /* call from the main loop                  */

#endif /* ASS2_H */
