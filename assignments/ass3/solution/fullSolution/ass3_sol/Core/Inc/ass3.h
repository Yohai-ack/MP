/**
 ******************************************************************************
 * @file    ass3.h
 * @brief   Assignment 3 reference solution: task numbers, buttons and shared
 *          helpers. TA ONLY, never handed to students.
 *
 *          One program. With the USB cable (wheels in the air, or the cart
 *          standing still) a task is chosen with `task` in Live Expressions.
 *          Without the cable, while idle, the IO-board buttons start the runs:
 *            button 0  A.3: speed step on the floor
 *            button 1  Part B: the obstacle course, 5 s after the press
 *            button 2  sends the data recorded in the last run (cable back in)
 *            button 3  emergency stop, read on every pass of every loop
 *
 *          The car in use is `carId` in main.c; its parameters (directions,
 *          counts per revolution, model, PI gains) come from car_params.c.
 ******************************************************************************
 */
#ifndef ASS3_H
#define ASS3_H

#include "main.h"
#include "car_params.h"
#include <stdint.h>

/* ------------------------------------------------------------------ */
/* tasks (write one into `task`) and buttons                           */
/* ------------------------------------------------------------------ */
enum
{
    TASK_IDLE = 0,
    TASK_A2   = 120,    /* A.2: speed step of all four wheels, in the air  */
    TASK_B2   = 220,    /* B.2: sensor measurements (own design)           */
    TASK_CAL  = 900     /* TA only: servo and IR calibration for car_params.c */
};

#define BTN_A3     0x01u    /* button 0 */
#define BTN_COURSE 0x02u    /* button 1 */
#define BTN_SEND   0x04u    /* button 2 */
#define BTN_STOP   0x08u    /* button 3: emergency stop */

extern volatile uint16_t task;       /* Live Expressions: what runs      */
extern const uint8_t     carId;      /* main.c: the car in use           */
extern const CarParams  *car;        /* its parameters (ass3_tasks.c)    */

/* timers generated by CubeMX in main.c */
extern TIM_HandleTypeDef htim1;      /* encoder of wheel 1 (rear right)  */
extern TIM_HandleTypeDef htim8;      /* encoder of wheel 2 (rear left)   */
extern TIM_HandleTypeDef htim3;      /* encoder of wheel 3 (front left)  */
extern TIM_HandleTypeDef htim4;      /* encoder of wheel 4 (front right) */
extern TIM_HandleTypeDef htim2;      /* motor PWM, 17 kHz                */
extern TIM_HandleTypeDef htim5;      /* ultrasonic trigger and echo      */
extern TIM_HandleTypeDef htim6;      /* 100 Hz control interrupt         */
extern I2C_HandleTypeDef hi2c1;

/* ------------------------------------------------------------------ */
/* constants that are the same on every car                            */
/* ------------------------------------------------------------------ */
#define PWM_FULL       10000u        /* TIM2 period + 1: CCR = 10000 is 100 % */
#define V_SUPPLY       12.0f         /* V at 100 % duty                       */
#define CTRL_DT        0.01f         /* s: TIM6, 100 Hz                       */
#define TWO_PI         6.2831853f
#define SPEED_FACTOR   0.9f          /* drive at 0.9 x the smallest maxVelCmdNoSat */

/* the cart (the same on every car; Yohai, 2026-11-07) */
#define WHEEL_RADIUS_M    0.030f     /* Mecanum wheel radius, m                 */
#define CAR_WHEELBASE_MM  165.0f     /* front to rear wheel centres, mm         */
#define CAR_TRACK_MM      210.0f     /* left to right wheel centres, mm         */
#define CAR_HALF_WIDTH_MM 120.0f     /* half the overall width (240 mm, outside
                                        of the wheels), to clear an obstacle  */
#define CAR_LENGTH_MM     300.0f     /* overall length, sensors to the rear   */

/* The Mecanum kinematics, NOT the choice of side (the course chooses the
   shorter side on its own): +1 if wheels 2 and 4 forward with 1 and 3
   backward moves the cart to its LEFT. +1 for rollers in the usual X pattern
   (seen from above); check it once on the floor.                              */
#define STRAFE_SIGN       (+1)

/* ------------------------------------------------------------------ */
/* ass3_tasks.c: dispatcher, buttons, emergency stop                   */
/* ------------------------------------------------------------------ */
void    ass3Init(void);
void    ass3Run(void);
uint8_t buttonsNew(void);            /* buttons pressed since the last call */
uint8_t keepGoing(uint16_t myTask);  /* read button 3 (at most every 10 ms);
                                        0 after an emergency stop or when
                                        `task` is no longer myTask           */
uint8_t waitGoing(uint16_t myTask, uint32_t ms);   /* wait, keepGoing inside */
uint8_t stopped(void);               /* 1 after an emergency stop           */
void    setStatusLed(uint8_t r, uint8_t g, uint8_t b);   /* all 8 RGB LEDs */
void    printFixed2(float value);    /* 12.34, no %f needed                 */

/* ------------------------------------------------------------------ */
/* ass3_wheels.c: motors, encoders, PI speed control at 100 Hz         */
/* ------------------------------------------------------------------ */
void  wheelsInit(void);              /* PWM at 0, encoders started          */
void  wheelsStart(void);             /* control on: setpoints 0, TIM6 on    */
void  wheelsStop(void);              /* control off, TIM6 off, all PWM 0    */
void  wheelsSample(void);            /* TIM6 callback: measure, PI, record  */
void  wheelsSetRef(const float ref[4]);   /* setpoints, rad/s, + forward    */
void  wheelsGetSpeed(float w[4]);    /* last measured speeds, rad/s         */
float wheelsVCmd(void);              /* 0.9 x the smallest maxVelCmdNoSat   */

/* motions without turning: all four wheels at +-vCmd, or 0 */
void  driveForward(int8_t dir);      /* +1 forward, -1 backward, 0 stop     */
void  driveSideways(int8_t dir);     /* +1 left, -1 right                   */
float odoForwardMm(void);            /* distance driven since odoReset      */
float odoLeftMm(void);
void  odoReset(void);

/* ------------------------------------------------------------------ */
/* ass3_io.c: IR sensor, sonar in mm, servo                            */
/* ------------------------------------------------------------------ */
uint8_t  irObstacle(void);
void     sonarOn(void);              /* interrupt mode                      */
void     sonarOff(void);
void     sonarOnReading(void);       /* from HAL_TIM_IC_CaptureCallback     */
uint8_t  sonarFresh(uint32_t maxAgeMs);   /* a reading newer than maxAgeMs  */
uint32_t sonarMm(void);              /* last reading, mm                    */
uint32_t sonarMedianMm(void);        /* median of the last 3 readings, mm   */
uint32_t sonarReadingCount(void);
void     servoInit(void);
void     servoSetUs(uint16_t us);    /* 900 .. 2100                         */
float    servoAngleDeg(uint16_t us); /* + to the left, from car->servoDeg   */
uint16_t servoAheadUs(void);         /* the pulse that looks straight ahead */
void     calibrate(void);            /* task 900 (TA): servo and IR         */

/* ------------------------------------------------------------------ */
/* ass3_record.c: run data in RAM that survives the reset of the cable  */
/* ------------------------------------------------------------------ */
enum { REC_NONE = 0, REC_A2 = 2, REC_A3 = 3, REC_B = 4 };
void    recStart(uint8_t kind);      /* forget the old run, start a new one */
void    recStop(void);               /* no more samples (data kept)         */
void    recSampleStep(float r, const float w[4], const float u[4]);   /* A  */
void    recSampleCourse(const int16_t dCounts[4], uint8_t state);     /* B  */
uint8_t recFull(void);
void    recSend(void);               /* print the kept run, MATLAB format   */
void    recBootCheck(void);          /* at start-up: say what RAM holds     */

/* ------------------------------------------------------------------ */
/* the parts                                                           */
/* ------------------------------------------------------------------ */
void    partA2(void);                /* task 120                            */
void    partA3(void);                /* button 0                            */
void    partB(void);                 /* button 1: the obstacle course       */
void    partB2(void);                /* task 220                            */
extern volatile uint8_t courseState; /* recorded with every B sample        */

#endif /* ASS3_H */
